#!/usr/bin/env python3
"""Geometry/control metrics for KIMODO-SMPLX control tasks (keyframe / trajectory
/ spatial) generated by ``gen_kimodo_m2m_smplx.py``.

Distribution metrics (FID / R@k / MM-Dist / Diversity) are produced separately
by ``eval_motionstreamer_272.py`` (it consumes ``motion_135`` row-major directly,
same as the temporal eval). This script reports the *control-accuracy* metrics
that distinguish each family, reusing the canonical implementations:

* keyframe : KPS Err (world-absolute joint error on the observed keyframes, cm),
             MPJPE (world-absolute, all frames, cm), Fail@20/50 (fraction of
             observed keyframes whose mean per-joint world error exceeds k cm),
             foot-skating ratio, 272-ric jitter.
* traj     : Traj.Err (pelvis L2 on the constrained XZ coords, metres),
             Fail@20/50 (fraction of constrained frames above 20/50 cm),
             foot-skating ratio, 272-ric jitter.
* spatial  : Ctrl.Err (mean geodesic rotation error on the observed/kept joints,
             degrees) via :func:`compute_rotation_ctrl_error`, foot-skating,
             272-ric jitter.

All world positions are obtained by FK on the *local* rot6d in ``motion_135``
(``rotation_space="local"``), matching how the model emits them.

Usage:
  python3 scripts/eval/eval_kimodo_m2m_smplx_control.py \
      --pred-dir outputs/.../keyframe/preds_npz --kind keyframe \
      --out      outputs/.../keyframe/metrics/control.json
"""
from __future__ import annotations

import argparse
import glob
import json
import os
import sys
from pathlib import Path

import numpy as np

_THIS_DIR = os.path.dirname(os.path.abspath(__file__))
_REPO_ROOT = os.path.abspath(os.path.join(_THIS_DIR, "..", ".."))
sys.path.insert(0, _THIS_DIR)
sys.path.insert(0, _REPO_ROOT)

import torch  # noqa: E402
from motionstreamer_272_encoder import motion135_to_272  # noqa: E402
from hftrainer.pipelines.motion.differentiable_fk import motion135_to_fk  # noqa: E402
from hftrainer.evaluation.motion.m2m_eval_metrics import (  # noqa: E402
    compute_foot_ground_metrics, compute_rotation_ctrl_error,
)

_BONE22 = torch.load(
    os.path.join(_REPO_ROOT, "data/hymotion_m2m_data/bone_offsets_22.pt"),
    map_location="cpu").float()
_NJ = 22


def _world(m135: np.ndarray) -> np.ndarray:
    t = torch.from_numpy(np.asarray(m135[:, :135], dtype=np.float32))
    wp, _, _, _ = motion135_to_fk(t, _BONE22, rotation_space="local")
    return wp.numpy()


def _pred_world(d) -> np.ndarray:
    """Predicted world joints.

    The generator already saves KIMODO's FK output as ``posed_joints``. Prefer
    that cached array to avoid re-running FK for thousands of samples during
    control evaluation. Fall back to FK for older npz files.
    """
    if "posed_joints" in d:
        return np.asarray(d["posed_joints"], dtype=np.float32)[:, :22]
    return _world(np.asarray(d["motion_135"], dtype=np.float32))


def _grounded(pos: np.ndarray) -> np.ndarray:
    pos = np.asarray(pos, dtype=np.float32).copy()
    pos[:, :, 1] -= pos[:, :, 1].min()
    return pos


def _ric(m272: np.ndarray) -> np.ndarray:
    T = m272.shape[0]
    return m272[:, 8:8 + 3 * _NJ].reshape(T, _NJ, 3)


def _jitter(pos: np.ndarray, fps: int = 30) -> float:
    if pos.shape[0] < 4:
        return 0.0
    acc = np.diff(pos, n=3, axis=0) * (fps ** 3)
    return float(np.linalg.norm(acc, axis=-1).mean())


def _common(d) -> dict:
    """Foot-skating (world, grounded) + jitter (272-ric)."""
    pred = np.asarray(d["motion_135"], dtype=np.float32)
    foot = compute_foot_ground_metrics(_grounded(_pred_world(d)), fps=30.0)
    jit = _jitter(_ric(motion135_to_272(pred)), 30)
    return {"foot_skating": float(foot["foot_skating_ratio"]), "jitter": jit}


def _eval_keyframe(d) -> dict:
    pred = np.asarray(d["motion_135"], dtype=np.float32)
    gt = np.asarray(d["gt_motion_135"], dtype=np.float32)
    cf = np.asarray(d["condition_frames"], dtype=np.int64)
    pw, gw = _pred_world(d), _world(gt)
    T = min(len(pw), len(gw))
    pw, gw = pw[:T], gw[:T]
    cf = cf[(cf >= 0) & (cf < T)]
    mpjpe_world = float(np.linalg.norm(pw - gw, axis=-1).mean())  # m
    per_kf = np.linalg.norm(pw[cf] - gw[cf], axis=-1).mean(axis=-1)  # (K,) m
    out = _common(d)
    out.update({
        "kps_err": float(per_kf.mean()),                 # m
        "mpjpe_world": mpjpe_world,                      # m
        "fail20": float(np.mean(per_kf * 100 > 20)),
        "fail50": float(np.mean(per_kf * 100 > 50)),
        "n_keyframes": int(len(cf)),
    })
    return out


def _eval_traj(d) -> dict:
    pred = np.asarray(d["motion_135"], dtype=np.float32)
    gt = np.asarray(d["gt_motion_135"], dtype=np.float32)
    cf = np.asarray(d["condition_frames"], dtype=np.int64)
    pw, gw = _pred_world(d), _world(gt)
    T = min(len(pw), len(gw))
    cf = cf[(cf >= 0) & (cf < T)]
    pel_p = pw[cf][:, 0][:, [0, 2]]
    pel_g = gw[cf][:, 0][:, [0, 2]]
    terr = np.linalg.norm(pel_p - pel_g, axis=-1)  # (K,) m
    out = _common(d)
    out.update({
        "traj_err": float(terr.mean()),                 # m
        "fail20": float(np.mean(terr > 0.20)),
        "fail50": float(np.mean(terr > 0.50)),
    })
    return out


def _eval_spatial(d) -> dict:
    pred = np.asarray(d["motion_135"], dtype=np.float32)
    gt = np.asarray(d["gt_motion_135"], dtype=np.float32)
    pm = np.asarray(d["part_mask_135"], dtype=np.float32)
    r = compute_rotation_ctrl_error(pred, gt, pm)
    out = _common(d)
    out["ctrl_err_deg"] = float(r.get("rot_ctrl_err_deg", float("nan")))
    out["n_kept_joints"] = int(len(np.asarray(d["kept_joints"])))
    return out


_EVAL = {"keyframe": _eval_keyframe, "traj": _eval_traj, "spatial": _eval_spatial}


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--pred-dir", required=True)
    ap.add_argument("--kind", required=True, choices=list(_EVAL))
    ap.add_argument("--out", required=True)
    ap.add_argument("--max-samples", type=int, default=0)
    args = ap.parse_args()

    files = sorted(glob.glob(os.path.join(args.pred_dir, "*.npz")))
    files = [f for f in files if not os.path.basename(f).startswith("_")]
    if args.max_samples:
        files = files[: args.max_samples]
    if not files:
        raise SystemExit(f"no npz under {args.pred_dir}")

    fn = _EVAL[args.kind]
    accum: dict = {}
    n = 0
    warned = False
    for i, f in enumerate(files):
        try:
            d = np.load(f, allow_pickle=True)
            r = fn(d)
        except Exception as e:  # noqa: BLE001
            if not warned:
                print(f"[warn] failed on {f}: {type(e).__name__}: {e}", flush=True)
                warned = True
            continue
        for k, v in r.items():
            accum.setdefault(k, []).append(v)
        n += 1
        if (i + 1) % 500 == 0:
            print(f"  {i+1}/{len(files)} kept={n}", flush=True)

    if n == 0:
        raise SystemExit("no valid npz evaluated")
    res = {"pred_dir": args.pred_dir, "kind": args.kind, "n_samples": n}
    for k, v in accum.items():
        res[k + "_mean"] = float(np.mean(v))

    # cm-converted convenience fields for table reading
    if args.kind == "keyframe":
        res["kps_err_cm"] = res["kps_err_mean"] * 100
        res["mpjpe_world_cm"] = res["mpjpe_world_mean"] * 100
    elif args.kind == "traj":
        res["traj_err_m"] = res["traj_err_mean"]

    Path(os.path.dirname(args.out) or ".").mkdir(parents=True, exist_ok=True)
    with open(args.out, "w") as fh:
        json.dump(res, fh, indent=2)

    print(f"\n=== KIMODO-SMPLX {args.kind} CONTROL METRICS  N={n} ===")
    if args.kind == "keyframe":
        print(f" KPS Err   = {res['kps_err_mean']*100:.1f} cm")
        print(f" MPJPE     = {res['mpjpe_world_mean']*100:.1f} cm (world, all frames)")
        print(f" Fail@20   = {res['fail20_mean']:.2f}")
        print(f" Fail@50   = {res['fail50_mean']:.2f}")
    elif args.kind == "traj":
        print(f" Traj.Err  = {res['traj_err_mean']:.3f} m")
        print(f" Fail@20   = {res['fail20_mean']:.3f}")
        print(f" Fail@50   = {res['fail50_mean']:.3f}")
    else:
        print(f" Ctrl.Err  = {res['ctrl_err_deg_mean']:.2f} deg (kept joints)")
    print(f" Foot      = {res['foot_skating_mean']:.3f}")
    print(f" Jitter    = {res['jitter_mean']:.1f}")
    print(f"[done] -> {args.out}")


if __name__ == "__main__":
    main()
